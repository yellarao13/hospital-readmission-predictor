print("\nReadmission percentage:")
print(round(df["readmitted_30_days"].mean() * 100, 2), "%")

print("\nMissing values:")
print(df.isnull().sum())

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

df = pd.read_csv("hospital_readmission_1000.csv")

print("Dataset loaded successfully!")
print("Shape:", df.shape)

df.head()

print("Number of rows and columns:", df.shape)

print("\nColumn names:")
print(df.columns.tolist())

print("\nData types and non-null values:")
df.info()

print("\nStatistical summary:")
display(df.describe(include="all"))

print("Missing values in each column:")
print(df.isnull().sum())

print("\nTotal missing values:")
print(df.isnull().sum().sum())

print("Duplicate rows:", df.duplicated().sum())

print("Duplicate patient IDs:", df["patient_id"].duplicated().sum())

# Remove extra spaces from column names
df.columns = df.columns.str.strip()

# Remove duplicate rows
df = df.drop_duplicates().copy()

# Remove duplicate patient IDs, keeping the first record
df = df.drop_duplicates(
    subset=["patient_id"], keep="first"
).copy()

# Convert numerical columns to numeric types
numeric_cols = [
    "age",
    "time_in_hospital",
    "previous_admissions",
    "num_lab_procedures",
    "num_medications",
    "readmitted_30_days"
]

for col in numeric_cols:
    df[col] = pd.to_numeric(df[col], errors="coerce")

# Remove records with missing patient ID or target
df = df.dropna(
    subset=["patient_id", "readmitted_30_days"]
).copy()

# Fill missing numerical values with median
for col in numeric_cols:
    if df[col].isnull().any():
        df[col] = df[col].fillna(df[col].median())

# Fill missing categorical values with most frequent value
categorical_cols = [
    "gender",
    "admission_type",
    "diagnosis",
    "diabetes",
    "medication_change",
    "discharge_disposition"
]

for col in categorical_cols:
    if df[col].isnull().any():
        mode = df[col].mode()
        if not mode.empty:
            df[col] = df[col].fillna(mode.iloc[0])

print("Data cleaning completed!")
print("Cleaned dataset shape:", df.shape)
print("Missing values remaining:", df.isnull().sum().sum())

print("Missing values:")
print(df.isnull().sum())

print("\nDuplicate rows:", df.duplicated().sum())

print("\nFirst five cleaned records:")
display(df.head())

print("\nReadmission counts:")
print(df["readmitted_30_days"].value_counts())

# Create a figure with 5 graphs
fig, axes = plt.subplots(2, 3, figsize=(18, 10))

# Graph 1: Readmission distribution
counts = df["readmitted_30_days"].value_counts().reindex(
    [0, 1], fill_value=0
)

axes[0, 0].bar(
    ["Not Readmitted", "Readmitted"],
    counts.values
)
axes[0, 0].set_title("Readmission Distribution")
axes[0, 0].set_ylabel("Number of Patients")
axes[0, 0].tick_params(axis="x", rotation=15)

# Graph 2: Age distribution
axes[0, 1].hist(df["age"], bins=15, edgecolor="black")
axes[0, 1].set_title("Age Distribution")
axes[0, 1].set_xlabel("Age")
axes[0, 1].set_ylabel("Number of Patients")

# Graph 3: Readmission by diagnosis
rates = (
    df.groupby("diagnosis")["readmitted_30_days"].mean() * 100
).sort_values(ascending=False)

axes[0, 2].bar(rates.index, rates.values)
axes[0, 2].set_title("Readmission Rate by Diagnosis")
axes[0, 2].set_ylabel("Readmission Rate (%)")
axes[0, 2].tick_params(axis="x", rotation=45)

# Graph 4: Average hospital stay
stay = df.groupby("readmitted_30_days")[
    "time_in_hospital"
].mean().reindex([0, 1])

axes[1, 0].bar(
    ["Not Readmitted", "Readmitted"],
    stay.values
)
axes[1, 0].set_title("Average Hospital Stay")
axes[1, 0].set_ylabel("Average Days")
axes[1, 0].tick_params(axis="x", rotation=15)

# Graph 5: Correlation heatmap
corr_cols = [
    "age",
    "time_in_hospital",
    "previous_admissions",
    "num_lab_procedures",
    "num_medications",
    "readmitted_30_days"
]

corr = df[corr_cols].corr()

im = axes[1, 1].imshow(
    corr, cmap="coolwarm", vmin=-1, vmax=1
)

axes[1, 1].set_title("Correlation Heatmap")
axes[1, 1].set_xticks(range(len(corr_cols)))
axes[1, 1].set_yticks(range(len(corr_cols)))
axes[1, 1].set_xticklabels(
    corr_cols, rotation=45, ha="right", fontsize=8
)
axes[1, 1].set_yticklabels(corr_cols, fontsize=8)

for i in range(len(corr_cols)):
    for j in range(len(corr_cols)):
        axes[1, 1].text(
            j, i, f"{corr.iloc[i, j]:.2f}",
            ha="center", va="center", fontsize=7
        )

fig.colorbar(im, ax=axes[1, 1], shrink=0.8)

# Hide the unused sixth plot
axes[1, 2].axis("off")

plt.tight_layout()
plt.show()

df.to_csv("cleaned_hospital_readmission.csv", index=False)

print("Cleaned dataset saved successfully!")

print("Final number of rows:", df.shape[0])
print("Final number of columns:", df.shape[1])

print(
    "Readmission percentage:",
    round(df["readmitted_30_days"].mean() * 100, 2),
    "%"
)

