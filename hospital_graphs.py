import pandas as pd
import numpy as np

# Reproducible synthetic data
np.random.seed(42)
n = 1000

# Generate patient features
age = np.random.randint(18, 91, n)

gender = np.random.choice(
    ["Male", "Female"], n
)

admission_type = np.random.choice(
    ["Emergency", "Urgent", "Elective"], n,
    p=[0.55, 0.25, 0.20]
)

diagnosis = np.random.choice(
    ["Diabetes", "Heart Disease", "Respiratory",
     "Kidney Disease", "Other"], n
)

time_in_hospital = np.random.randint(1, 15, n)
previous_admissions = np.random.poisson(1.2, n)
num_lab_procedures = np.random.randint(1, 100, n)
num_medications = np.random.randint(1, 40, n)

diabetes = np.random.choice(
    ["Yes", "No"], n, p=[0.65, 0.35]
)

medication_change = np.random.choice(
    ["Yes", "No"], n, p=[0.45, 0.55]
)

discharge_disposition = np.random.choice(
    ["Home", "Rehabilitation", "Other"],
    n, p=[0.75, 0.15, 0.10]
)

# Create a synthetic probability of readmission.
# These weights are illustrative, not medically validated.
log_odds = (
    -2.0
    + 0.035 * (age - 50)
    + 0.22 * previous_admissions
    + 0.07 * time_in_hospital
    + 0.30 * (diabetes == "Yes")
    + 0.35 * (medication_change == "Yes")
    + 0.40 * (admission_type == "Emergency")
    + 0.45 * (discharge_disposition == "Rehabilitation")
)

probability = 1 / (1 + np.exp(-log_odds))

# Binary target: 1 = readmitted, 0 = not readmitted
readmitted = np.random.binomial(1, probability)

# Build the dataset
df = pd.DataFrame({
    "patient_id": range(1001, 1001 + n),
    "age": age,
    "gender": gender,
    "admission_type": admission_type,
    "diagnosis": diagnosis,
    "time_in_hospital": time_in_hospital,
    "previous_admissions": previous_admissions,
    "num_lab_procedures": num_lab_procedures,
    "num_medications": num_medications,
    "diabetes": diabetes,
    "medication_change": medication_change,
    "discharge_disposition": discharge_disposition,
    "readmitted_30_days": readmitted
})

# Save as a CSV file
df.to_csv("hospital_readmission_1000.csv", index=False)

# Display results
print("Dataset generated successfully!")
